import puppeteer from "puppeteer-core";
const [url, dir] = process.argv.slice(2);
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 900 });
await p.goto(url, { waitUntil: "networkidle0" });
await p.evaluate(() => document.querySelectorAll("[data-reveal]").forEach((e) => e.classList.add("is-in")));
const f = await p.$("footer");
await f.screenshot({ path: `${dir}/footer.png` });
await p.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
await p.goto(url, { waitUntil: "networkidle0" });
await new Promise((r) => setTimeout(r, 1300));
await p.screenshot({ path: `${dir}/mobile.png` });
const big = await b.newPage();
await big.setViewport({ width: 520, height: 160, deviceScaleFactor: 2 });
await big.goto(url, { waitUntil: "networkidle0" });
await big.evaluate(() => { const l = document.querySelector(".nav .brand").cloneNode(true); document.body.innerHTML = ""; document.body.style.cssText = "margin:0;display:grid;place-items:center;height:100vh;background:#fff"; l.style.transform = "scale(2.2)"; document.body.append(l); });
await big.screenshot({ path: `${dir}/logo.png` });
await b.close();
